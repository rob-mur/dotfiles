#!/usr/bin/env python3
"""Mine candidate dictation vocabulary from your own Claude Code prompts.

Reads user-typed text (not tool output, not assistant text) from
~/.claude/projects/**/*.jsonl, drops anything found in an English wordlist,
and ranks the rest by how many distinct sessions use it, so one pasted log
cannot dominate. Only the ranked words are printed; no chat text is kept.

  d=$(nix build --no-link --print-out-paths nixpkgs#scowl)/share/dict
  python3 -I mine-vocab.py --out mined-terms.nix --wordlist \
      $d/wamerican.70 $d/wbritish.70 $d/wamerican.acceptable.70

Deterministic: same inputs give the same output. Edit EXCLUDE to veto
false positives (typos, ids, usernames) and re-run.
"""
import argparse
import json
import re
import sys
from collections import Counter
from pathlib import Path

# Candidates that pass the filters but are not worth biasing the model for.
# Ordinary or well-known words Whisper spells correctly anyway, inflections of
# a kept base form, split fragments of hyphenated words, ids and usernames.
EXCLUDE = set(
    """
    pre dev env sed txt perf cmd pid ack eval clarob config lifecycle rollout
    mergeable docstring subtask subtasks filesystem unmerged yolo teardown
    backend json csv csvs readme cli sdk kpi wip prd cwd bpc iac toolchain
    codebase devops repos worktrees rebased rebasing rebases subshells xdg
    dogfood yml wgf substring writeback kpis repo devtools xdev maxdepth nthe yyyy ast afk sigkill
    """.split()
)

# Hyphenated compounds are split so each part is judged on its own; the
# apostrophe tail is kept so contractions ("doesn't") match the wordlist.
TOKEN = re.compile(r"[A-Za-z][A-Za-z]*(?:['’][a-z]+)?")
STRIP = [
    re.compile(r"```.*?```", re.S),  # code fences
    re.compile(r"<[a-zA-Z_-]+>.*?</[a-zA-Z_-]+>", re.S),  # injected tags
    re.compile(r"https?://\S+"),
    re.compile(r"[~/.\w-]*/[\w./-]+"),  # paths
    re.compile(r"\b[0-9a-f]{7,}\b"),  # hashes
    re.compile(r"\S+@\S+"),
]


def user_texts(path):
    with open(path, errors="replace") as fh:
        for line in fh:
            try:
                e = json.loads(line)
            except ValueError:
                continue
            if e.get("type") != "user" or e.get("isMeta") or e.get("isSidechain"):
                continue
            c = (e.get("message") or {}).get("content")
            if isinstance(c, str):
                yield c
            elif isinstance(c, list):
                for b in c:
                    if isinstance(b, dict) and b.get("type") == "text":
                        yield b.get("text", "")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--wordlist", required=True, nargs="+")
    ap.add_argument("--projects", default=str(Path.home() / ".claude/projects"))
    ap.add_argument("--top", type=int, default=50)
    ap.add_argument("--min-sessions", type=int, default=3)
    ap.add_argument("--out", help="write a Nix list here (default: print)")
    a = ap.parse_args()

    known = set()
    for w in a.wordlist:
        for x in Path(w).read_text(errors="replace").split():
            x = x.lower()
            known.add(x)
            known.add(x.replace("'s", "").replace("'", ""))

    sessions = Counter()
    total = Counter()
    forms = {}
    for f in sorted(Path(a.projects).glob("**/*.jsonl")):
        seen = set()
        for t in user_texts(f):
            if t.lstrip().startswith(("<", "Caveat:", "[Request")):
                continue
            for rx in STRIP:
                t = rx.sub(" ", t)
            for m in TOKEN.findall(t):
                k = m.lower().replace("’", "'")
                if k in known or k.replace("'", "") in known:
                    continue
                if not (3 <= len(k) <= 20) or "'" in k or k in EXCLUDE:
                    continue
                # plural / possessive of a known word
                if k.endswith("s") and k[:-1] in known:
                    continue
                total[k] += 1
                seen.add(k)
                forms.setdefault(k, Counter())[m] += 1
        sessions.update(seen)

    # Most common spelling wins, but proper-cased forms (YouTrack, NixOS) count
    # triple so a lazily typed "youtrack" does not hide the real name.
    def weight(c, m):
        return c[m] * (1 if m.islower() or m.isupper() else 3)

    form = {k: max(c, key=lambda m: (weight(c, m), m)) for k, c in forms.items()}
    ranked = sorted(
        (k for k in sessions if sessions[k] >= a.min_sessions),
        key=lambda k: (-sessions[k], -total[k], k),
    )[: a.top]
    for k in ranked:
        print(f"{sessions[k]:5d} {total[k]:6d} {form[k]}", file=sys.stderr)
    if a.out:
        body = "".join(f'  "{form[k]}"\n' for k in ranked)
        Path(a.out).write_text(
            "# Generated by mine-vocab.py; edit EXCLUDE there, not this file.\n"
            f"[\n{body}]\n"
        )


if __name__ == "__main__":
    main()
